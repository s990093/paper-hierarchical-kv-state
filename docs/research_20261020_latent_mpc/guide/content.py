W = 487  # 內文寬度（pt）


def ev(s):
    return '<span class="ev">〔' + s + '〕</span>'


def fig(name, cap, w=W):
    return ('<p class="figp"><img src="' + name + '" width="' + str(w) + '"/></p>'
            '<p class="cap">' + cap + '</p>')


def paperfig(name, cap, src, w=W):
    return fig(name, cap + '<br/>圖片來源：' + src + '（原論文截圖，僅供學習導讀，請勿公開轉貼）', w)


def box(cls, html):
    return '<div class="' + cls + '">' + html + '</div>'


def table(head, rows, cls="t", widths=None):
    h = '<table class="' + cls + '"><tr>'
    for i, c in enumerate(head):
        wa = (' width="' + str(widths[i]) + '"') if widths else ''
        h += '<th' + wa + '>' + c + '</th>'
    h += '</tr>'
    for r in rows:
        h += '<tr>' + ''.join('<td>' + str(c) + '</td>' for c in r) + '</tr>'
    return h + '</table>'


def meta(rows):
    return table(["項目", "內容"], rows, cls="meta", widths=[90, 397])


def card(hid, title, metarows, oneliner, sections):
    h = '<h2 id="' + hid + '">' + title + '</h2>' + meta(metarows)
    h += box("key", '<p><b>一句話：</b>' + oneliner + '</p>')
    for t, body in sections:
        h += '<h3>' + t + '</h3>' + body
    return h


CHAPTERS = []


def add(html, newpage=True):
    CHAPTERS.append((html, newpage))


